#!/usr/bin/env python3
"""Extract SMuFL music-notation glyph outlines from the Bravura font into a JS module.

Why: the sheet music needs *accurate* musical shapes (grand-staff brace, treble/bass
clefs, key-signature sharps, time signatures). Unicode characters render differently on
every machine and are often missing entirely, so we ship the real engraved outlines as
SVG paths instead.

Source font: Bravura (Steinberg Media Technologies GmbH), SIL Open Font License 1.1.
The generated file contains outline data only -- see NOTICE-BRAVURA.md.

Usage:
    python tools/extract_bravura_glyphs.py <Bravura.otf> <Bravura.json> <out.js>
"""
import json
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.misc.transform import Identity
from fontTools.ttLib import TTFont

# SMuFL codepoints -> descriptive name used by the renderer.
# https://www.w3.org/2021/03/smufl14/tables/...
GLYPHS = {
    "brace":            0xE000,
    "braceSmall":       0xE002,
    "gClef":            0xE050,
    "fClef":            0xE062,
    "timeSig0":         0xE080,
    "timeSig1":         0xE081,
    "timeSig2":         0xE082,
    "timeSig3":         0xE083,
    "timeSig6":         0xE086,
    "timeSig8":         0xE088,
    "noteheadBlack":    0xE0A4,
    "noteheadHalf":     0xE0A3,
    "accidentalSharp":  0xE262,
    "accidentalNatural": 0xE261,
    "augmentationDot":  0xE1E7,
    "flag8thUp":        0xE240,
    "flag8thDown":      0xE241,
}


def smufl_units_per_em(otf):
    """Read the SMuFL 'units per em' from the OS/2 table (falls back to head.unitsPerEm)."""
    try:
        return otf["OS/2"].sxHeight or 0
    except Exception:
        return 0


def main():
    if len(sys.argv) != 4:
        print(__doc__)
        return 1
    otf_path, json_path, out_path = sys.argv[1], sys.argv[2], sys.argv[3]

    otf = TTFont(otf_path)
    upem = otf["head"].unitsPerEm
    glyph_set = otf.getGlyphSet()

    # SMuFL fonts define one staff space as 1/4 em. Normalising the outlines to staff
    # spaces means the bBoxSW/bBoxNE values from Bravura.json apply to the path as-is.
    units_per_space = upem / 4.0

    # Prefer the format-12 cmap (BMP only subtables miss the U+1D1xx range).
    cmap = {}
    for sub in otf["cmap"].tables:
        if sub.format == 12:
            cmap.update(sub.cmap)

    meta = json.load(open(json_path, encoding="utf-8"))
    bboxes = meta["glyphBBoxes"]

    out = {}
    for name, cp in GLYPHS.items():
        gname = cmap.get(cp)
        if gname is None:
            print(f"  !! missing {name} (U+{cp:04X})", file=sys.stderr)
            continue
        pen = SVGPathPen(glyph_set)
        # Font coordinates are y-up with the origin on the baseline; flip to SVG y-down
        # and scale font units -> staff spaces, so a path dropped at the glyph's origin
        # lands correctly with the bBox metadata from Bravura.json.
        flip = Identity.scale(1.0 / units_per_space, -1.0 / units_per_space)
        glyph_set[gname].draw(TransformPen(pen, flip))
        path = pen.getCommands()

        # Bounding box in staff spaces, relative to the glyph origin (SMuFL units).
        bb = bboxes.get(name)
        if bb is None:
            print(f"  !! no bBox for {name}", file=sys.stderr)
            continue
        out[name] = {
            "d": path,
            "sw": bb["bBoxSW"],
            "ne": bb["bBoxNE"],
        }

    # Also export the engraving defaults the layout math needs.
    ed = meta.get("engravingDefaults", {})
    out["_meta"] = {
        "staffLineThickness": ed.get("staffLineThickness"),
        "stemThickness": ed.get("stemThickness"),
        "unitsPerEm": upem,
    }

    header = (
        "// AUTO-GENERATED by tools/extract_bravura_glyphs.py -- do not edit by hand.\n"
        "// Glyph outlines from the Bravura music font (Steinberg Media Technologies GmbH),\n"
        "// SIL Open Font License 1.1 -- see NOTICE-BRAVURA.md for the full notice.\n"
        "//\n"
        "// Coordinates: SMuFL staff spaces. Origin = the point where the glyph sits\n"
        "// (clefs: their staff line). 1 unit = 1 staff space. bBoxSW/bBoxNE describe the\n"
        "// glyph extents relative to that origin, so the renderer can place glyphs exactly.\n"
    )
    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(header)
        fh.write("window.App = window.App || {};\n")
        fh.write("window.App.Glyphs = ")
        json.dump(out, fh, ensure_ascii=False, indent=1)
        fh.write(";\n")

    print(f"wrote {out_path} with {len(out) - 1} glyphs (upem={upem})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
