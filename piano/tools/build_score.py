#!/usr/bin/env python3
"""Wrap a score JSON file in a <script>-loadable global.

Browsers refuse `fetch()` on local files, so a score stored as JSON cannot be read
when index.html is opened by double-clicking. Emitting a tiny .js file instead means
the page works identically from file:// and from a local server.

Usage:
    python tools/build_score.py music-sheet/flower_day.json music-sheet/flower-day.js
"""
import json
import sys

GLOBAL_NAME = "FLOWER_DAY_SCORE"


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 1

    source, target = sys.argv[1], sys.argv[2]
    with open(source, encoding="utf-8") as fh:
        data = json.load(fh)

    header = (
        "// AUTO-GENERATED by tools/build_score.py from " + source.split("/")[-1] + "\n"
        "// Edit the .json file, then re-run the script -- never edit this file.\n"
        "// Loaded as a plain <script> so the page also works when opened from file://.\n"
    )

    with open(target, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(header)
        fh.write("window." + GLOBAL_NAME + " = ")
        json.dump(data, fh, ensure_ascii=False, separators=(",", ":"))
        fh.write(";\n")

    print("wrote " + target + " (" + str(len(data.get("measures", []))) + " measures)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
